// Generates src/engine/text/standard-metrics.js: the 14 standard PDF fonts' metrics (Adobe's AFM data) as plain
// tables, read from @pdf-lib/standard-fonts once here instead of decompressed with pako at every cold start (N43).
// Only what src/engine/text/standard.js reads: the widths by code, the encodings, and the font-wide numbers (no
// kerning: the engine does not kern the standard fonts). --check: exit 1 when the file on disk differs (CI).
import fs from 'node:fs';
import path from 'node:path';
import { Font, Encodings } from '@pdf-lib/standard-fonts';
import { STANDARD_FACES } from '../src/engine/text/standard.js';

const OUT = path.join(import.meta.dirname, '..', 'src/engine/text/standard-metrics.js');
const version = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, '..', 'node_modules/@pdf-lib/standard-fonts/package.json'), 'utf8')).version;
const encOf = (key) => (key === 'Symbol' || key === 'ZapfDingbats' ? key : 'WinAnsi');

/** encoding → [code point, code, …] in the order the encoding lists them (a soft hyphen is drawn as nothing: left out) */
const encodings = {};
for (const name of ['WinAnsi', 'Symbol', 'ZapfDingbats']) {
  encodings[name] = Object.entries(Encodings[name].unicodeMappings).filter(([cp]) => cp !== '173').flatMap(([cp, [code]]) => [Number(cp), code]);
}
const fonts = {};
for (const [, key] of STANDARD_FACES) {
  const afm = Font.load(key), enc = Encodings[encOf(key)];
  const widths = new Array(256).fill(0);
  for (const [cp, [code, name]] of Object.entries(enc.unicodeMappings)) if (cp !== '173') widths[code] = afm.CharWidths[name] ?? 250; // pdf-lib's default for a glyph the AFM lacks
  const [x0, y0, x1, y1] = afm.FontBBox;
  fonts[key] = {
    encoding: encOf(key), familyName: afm.FamilyName,
    ascent: afm.Ascender ?? y1, descent: afm.Descender ?? y0, capHeight: afm.CapHeight ?? y1, xHeight: afm.XHeight ?? 0,
    italicAngle: Number(afm.ItalicAngle) || 0, underlinePosition: afm.UnderlinePosition ?? -100, underlineThickness: afm.UnderlineThickness ?? 50,
    bbox: [x0, y0, x1, y1], widths,
  };
}
const wrap = (a) => a.join(',').replace(/((?:[^,]*,){32})/g, '$1\n    ');
const src = `// Generated by scripts/gen-standard-metrics.mjs from @pdf-lib/standard-fonts ${version}: Adobe's AFM metrics for the
// 14 standard PDF fonts (see THIRD-PARTY-NOTICES.md). Do not edit; run the script.

/** encoding → [code point, code, …] (WinAnsi without the soft hyphen, which is drawn as nothing) */
export const ENCODINGS = {
${Object.entries(encodings).map(([k, v]) => `  ${k}: [\n    ${wrap(v)}],`).join('\n')}
};
/** PostScript name → the font's metrics (units per em 1000); widths: the advance of each code in its encoding */
export const METRICS = {
${Object.entries(fonts).map(([k, { widths, bbox, ...f }]) => `  '${k}': { ${Object.entries(f).map(([p, v]) => `${p}: ${JSON.stringify(v)}`).join(', ')}, bbox: ${JSON.stringify(bbox)},\n    widths: [${wrap(widths)}] },`).join('\n')}
};
`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== src) { console.error('src/engine/text/standard-metrics.js is out of date: run node scripts/gen-standard-metrics.mjs'); process.exit(1); }
} else {
  fs.writeFileSync(OUT, src);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${(src.length / 1024).toFixed(1)} KB)`);
}
